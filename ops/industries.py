def profile(scope_or_conn, cid=None):
    conn = getattr(scope_or_conn, "conn", scope_or_conn)
    cid = cid if cid is not None else scope_or_conn.cid
    row = conn.execute("SELECT industry FROM clients WHERE id=?", (cid,)).fetchone()
    return PROFILES.get(row["industry"] if row and row["industry"] else "service", PROFILES["service"])
